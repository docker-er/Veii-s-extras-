using MediaBrowser.Model.Plugins;

namespace Jellyfin.Plugin.Popups.Configuration;

/// <summary>
/// Allowed values for <see cref="PopupDefinition.Audience"/>.
/// </summary>
public static class AudienceKind
{
    /// <summary>Every signed-in user.</summary>
    public const string Everyone = "everyone";

    /// <summary>Administrators only.</summary>
    public const string Admins = "admins";

    /// <summary>Everyone except administrators.</summary>
    public const string NonAdmins = "nonadmins";

    /// <summary>Only the users listed in <see cref="PopupDefinition.UserIds"/>.</summary>
    public const string Selected = "selected";
}

/// <summary>
/// Allowed values for <see cref="PopupDefinition.Frequency"/>.
/// </summary>
public static class FrequencyKind
{
    /// <summary>Every time the user enters the web client or app.</summary>
    public const string Always = "always";

    /// <summary>Only the first time, per user (until the popup revision changes).</summary>
    public const string Once = "once";
}

/// <summary>
/// One popup. Every content field is optional, so a popup can be plain text,
/// an image, a library item card, or any mix of them.
/// </summary>
public class PopupDefinition
{
    /// <summary>Gets or sets the stable id (generated by the admin page).</summary>
    public string Id { get; set; } = string.Empty;

    /// <summary>Gets or sets a value indicating whether the popup is live.</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>Gets or sets the internal name shown in the admin list.</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>Gets or sets the small tag above the title (for example NEWS).</summary>
    public string Label { get; set; } = string.Empty;

    /// <summary>Gets or sets the headline.</summary>
    public string Title { get; set; } = string.Empty;

    /// <summary>Gets or sets the text. Supports blank-line paragraphs, **bold** and [text](url).</summary>
    public string Body { get; set; } = string.Empty;

    /// <summary>Gets or sets an optional image address (http, https or a path on this server).</summary>
    public string ImageUrl { get; set; } = string.Empty;

    /// <summary>Gets or sets an optional library item id to show as a card.</summary>
    public string ItemId { get; set; } = string.Empty;

    /// <summary>Gets or sets the optional button text.</summary>
    public string ButtonText { get; set; } = string.Empty;

    /// <summary>Gets or sets the optional button address.</summary>
    public string ButtonUrl { get; set; } = string.Empty;

    /// <summary>Gets or sets who can see it. See <see cref="AudienceKind"/>.</summary>
    public string Audience { get; set; } = AudienceKind.Everyone;

    /// <summary>Gets or sets the users (ids) for <see cref="AudienceKind.Selected"/>.</summary>
    public List<string> UserIds { get; set; } = new();

    /// <summary>Gets or sets where it appears: all, mobile or desktop.</summary>
    public string Device { get; set; } = "all";

    /// <summary>Gets or sets how often it appears. See <see cref="FrequencyKind"/>.</summary>
    public string Frequency { get; set; } = FrequencyKind.Always;

    /// <summary>Gets or sets the card size: compact, standard or wide.</summary>
    public string Size { get; set; } = "standard";

    /// <summary>Gets or sets an optional accent color like #e50914 (empty uses the theme red).</summary>
    public string AccentColor { get; set; } = string.Empty;

    /// <summary>Gets or sets the ISO start time (UTC). Empty means no start limit.</summary>
    public string StartsAtUtc { get; set; } = string.Empty;

    /// <summary>Gets or sets the ISO end time (UTC). Empty means no end limit.</summary>
    public string EndsAtUtc { get; set; } = string.Empty;

    /// <summary>Gets or sets the order; higher shows first.</summary>
    public int Priority { get; set; }

    /// <summary>Gets or sets the revision. Raising it shows a "once" popup again to everyone.</summary>
    public int Revision { get; set; } = 1;
}

/// <summary>
/// Plugin configuration.
/// </summary>
public class PluginConfiguration : BasePluginConfiguration
{
    /// <summary>Gets or sets a value indicating whether the plugin does anything (master kill switch).</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>Gets or sets the most popups shown in one visit.</summary>
    public int MaxPerVisit { get; set; } = 3;

    /// <summary>Gets or sets the pause, in seconds, between the app loading and the first popup.</summary>
    public int ShowDelaySeconds { get; set; } = 1;

    /// <summary>Gets or sets a value indicating whether clicking outside the card closes it.</summary>
    public bool CloseOnBackdropClick { get; set; } = true;

    /// <summary>Gets or sets the popups.</summary>
    public List<PopupDefinition> Popups { get; set; } = new();

    /// <summary>Gets or sets a value indicating whether users can send private messages (Asks).</summary>
    public bool AsksEnabled { get; set; } = true;

    /// <summary>Gets or sets a value indicating whether the floating Asks button is shown.</summary>
    public bool AsksShowButton { get; set; } = true;

    /// <summary>Gets or sets where the floating button sits: bottom-right or bottom-left.</summary>
    public string AsksButtonPosition { get; set; } = "bottom-right";

    /// <summary>Gets or sets the text on the floating button and the panel title.</summary>
    public string AsksButtonText { get; set; } = "Asks";

    /// <summary>Gets or sets a short line shown at the top of the Asks form.</summary>
    public string AsksIntro { get; set; } = string.Empty;

    /// <summary>Gets or sets a value indicating whether users can attach photos.</summary>
    public bool AsksAllowImages { get; set; } = true;

    /// <summary>Gets or sets the most messages one user can send per hour.</summary>
    public int AsksMaxPerHour { get; set; } = 5;
}
